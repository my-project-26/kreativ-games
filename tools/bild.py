def finde(regeln, text):
    for rx, e in regeln:
        if re.search(rx, text):
            return e
    return ""

def main(write):
    s = open(P).read()
    arr = json.loads(s[s.index("["):s.rindex("]") + 1])
    ohne = []
    for i in arr:
        if i["art"] != "Basteln":
            i.pop("bild", None); i.pop("bildTechnik", None)
            continue
        name = i["name"].lower()
        m = finde(MOTIV, name) or finde(MOTIV, (i.get("beschreibung", "")).lower())
        if not m:
            ohne.append(i["name"]); m = "✂️"
        t = finde(TECHNIK, name) or finde(TECHNIK, i.get("material", "").lower())
        if t and t in m: t = ""
        i["bild"] = m
        if t: i["bildTechnik"] = t
        else: i.pop("bildTechnik", None)
    print("ohne Motiv:", len(ohne), ohne)
    if write:
        open(P, "w").write("const IDEEN = " + json.dumps(arr, ensure_ascii=False, indent=1) + ";\n")

main("--write" in sys.argv)
